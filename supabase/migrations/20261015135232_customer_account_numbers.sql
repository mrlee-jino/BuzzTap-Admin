-- Customer identifiers are independent of physical NFC cards.
create schema if not exists app_private;
revoke all on schema app_private from public, anon, authenticated;

alter table public.profiles
  add column account_number text unique,
  add column account_region text check (account_region ~ '^[0-9]{2}$' and account_region <> '00'),
  add constraint profiles_account_number_format check (account_number ~ '^[0-9]{16}$');

create table app_private.account_region_counters (
  region text primary key check (region ~ '^[0-9]{2}$' and region <> '00'),
  last_number integer not null check (last_number between 1 and 999999)
);
-- Keep reservations even if a profile is deleted, so identifiers are never reused.
create table app_private.account_number_reservations (
  account_number text primary key,
  customer_id uuid not null unique
);
alter table app_private.account_region_counters enable row level security;
alter table app_private.account_number_reservations enable row level security;
revoke all on all tables in schema app_private from public, anon, authenticated;

create function app_private.set_customer_account_number()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  candidate text;
  sequence_number integer;
  attempt integer;
  reserved text;
begin
  if TG_OP = 'UPDATE' and OLD.account_number is not null then
    if NEW.account_number is distinct from OLD.account_number
       or NEW.account_region is distinct from OLD.account_region
       or NEW.created_at is distinct from OLD.created_at then
      raise exception 'An assigned account number, registration date and region cannot be changed';
    end if;
    return NEW;
  end if;
  if NEW.account_number is not null then
    raise exception 'Account numbers must be generated by the database';
  end if;
  if NEW.role <> 'CUSTOMER' or NEW.account_region is null then
    return NEW;
  end if;
  if NEW.account_region !~ '^[0-9]{2}$' or NEW.account_region = '00' then
    raise exception 'Enter a two-digit region code from 01 to 99';
  end if;
  if NEW.created_at is null then
    raise exception 'Customer registration date is required';
  end if;

  -- Updating one counter row serializes concurrent allocations in that region.
  for attempt in 1..999999 loop
    insert into app_private.account_region_counters as counters (region, last_number)
    values (NEW.account_region, 1)
    on conflict (region) do update
      set last_number = (counters.last_number % 999999) + 1
    returning last_number into sequence_number;

    candidate := to_char(NEW.created_at at time zone 'Asia/Manila', 'YYYYMMDD')
      || NEW.account_region || lpad(sequence_number::text, 6, '0');
    insert into app_private.account_number_reservations (account_number, customer_id)
    values (candidate, NEW.id)
    on conflict (account_number) do nothing
    returning account_number into reserved;
    if reserved is not null then
      NEW.account_number := reserved;
      return NEW;
    end if;
  end loop;
  raise exception 'All account numbers for this registration date and region are already used';
end;
$$;
revoke all on function app_private.set_customer_account_number() from public, anon, authenticated;

create trigger profiles_customer_account_number
before insert or update on public.profiles
for each row execute function app_private.set_customer_account_number();

-- Approved default for existing customers only; new accounts require a region.
do $$
declare customer record;
begin
  for customer in select id from public.profiles where role = 'CUSTOMER' order by created_at, id loop
    update public.profiles set account_region = '13' where id = customer.id;
  end loop;
end;
$$;

create function public.admin_assign_customer_account_number(p_customer_id uuid, p_region text)
returns text language plpgsql security definer set search_path = '' as $$
declare customer public.profiles;
begin
  if (select auth.uid()) is null or not public.is_admin() then
    raise exception using errcode = '42501', message = 'Active admin access required';
  end if;
  if p_region is null or p_region !~ '^[0-9]{2}$' or p_region = '00' then
    raise exception 'Enter a two-digit region code from 01 to 99';
  end if;
  select * into customer from public.profiles where id = p_customer_id and role = 'CUSTOMER' for update;
  if not found then raise exception 'Customer not found'; end if;
  if customer.account_number is not null then return customer.account_number; end if;
  update public.profiles set account_region = p_region where id = p_customer_id returning * into customer;
  insert into public.audit_logs (actor_user_id, action, target_type, target_id, details)
  values ((select auth.uid()), 'CUSTOMER_ACCOUNT_NUMBER_ASSIGNED', 'CUSTOMER', customer.id,
    jsonb_build_object('account_number', customer.account_number, 'region', p_region));
  return customer.account_number;
end;
$$;
revoke all on function public.admin_assign_customer_account_number(uuid, text) from public, anon;
grant execute on function public.admin_assign_customer_account_number(uuid, text) to authenticated;
notify pgrst, 'reload schema';
